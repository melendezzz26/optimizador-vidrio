"""Caller-owned transactional ports. No ORM or Orders infrastructure imports."""
from typing import Protocol
from decimal import Decimal
from ..domain.problem import OptimizationProblem, OptimizationConfig, OptimizationResult
from .dto import OptimizationRun
from .confirmation import ConfirmationContext, ConfirmationResult, CreatedRemnant
from ..domain.confirmation import MaterialConsumption
from ..domain.metrics import ResidualRectangle


class OrdersBatch(Protocol):
    def lock_pending(self, order_ids: tuple[int, ...]) -> list[dict]: ...
    def require_state(self, order_ids: tuple[int, ...], expected: str) -> None: ...
    def transition(self, order_ids: tuple[int, ...], expected: str, target: str) -> None: ...


class RunRepository(Protocol):
    def create(self, problem: OptimizationProblem, configuration_id: int, actor_id: int) -> OptimizationRun: ...
    def get(self, optimization_id: int) -> OptimizationRun: ...
    def fail(self, optimization_id: int, code: str, placements: tuple = ()) -> OptimizationRun: ...
    def residual_limits(self, optimization_id: int) -> tuple[Decimal, Decimal]: ...
    def save_result(self, optimization_id: int, result: OptimizationResult, residuals: tuple) -> OptimizationRun: ...


class ConfirmationRepository(Protocol):
    def lock_run(self, optimization_id: int) -> ConfirmationContext: ...
    def lock_and_revalidate(self, consumptions: tuple[MaterialConsumption, ...], context: ConfirmationContext) -> None: ...
    def consume(self, consumptions: tuple[MaterialConsumption, ...]) -> None: ...
    def record_movements(self, consumptions: tuple[MaterialConsumption, ...], optimization_id: int, actor_id: int) -> None: ...
    def create_residuals(self, residuals: tuple[ResidualRectangle, ...], context: ConfirmationContext) -> tuple[CreatedRemnant, ...]: ...
    def mark_confirmed(self, context: ConfirmationContext, receipt: ConfirmationResult, actor_id: int) -> None: ...


class RunUnitOfWork(Protocol):
    orders: OrdersBatch
    runs: RunRepository
    confirmation: ConfirmationRepository
    def configuration(self) -> tuple[int, OptimizationConfig]: ...
    def __enter__(self) -> "RunUnitOfWork": ...
    def __exit__(self, exc_type, exc, traceback) -> None: ...
