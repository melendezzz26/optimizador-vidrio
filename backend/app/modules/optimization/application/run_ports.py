"""Caller-owned transactional ports. No ORM or Orders infrastructure imports."""
from typing import Protocol
from ..domain.problem import OptimizationProblem
from .dto import OptimizationRun


class OrdersBatch(Protocol):
    def lock_pending(self, order_ids: tuple[int, ...]) -> list[dict]: ...
    def transition(self, order_ids: tuple[int, ...], expected: str, target: str) -> None: ...


class RunRepository(Protocol):
    def create(self, problem: OptimizationProblem, configuration_id: int, actor_id: int) -> OptimizationRun: ...
    def get(self, optimization_id: int) -> OptimizationRun: ...


class RunUnitOfWork(Protocol):
    orders: OrdersBatch
    runs: RunRepository
    def configuration(self) -> tuple[int, object]: ...
    def __enter__(self) -> "RunUnitOfWork": ...
    def __exit__(self, exc_type, exc, traceback) -> None: ...
